// Regenerates Assets/Avatars and Controls/MaterialAvatarData.cs from the anonymized design
// export. Every exported avatar photograph (1080 x 1080, about 1.3 MB each) is copied
// byte-for-byte from the source package, so the library keeps the original visual data,
// color profile and alpha channel without any resampling or recompression.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../../artifacts/design-system-anonymized');
const outAssets = path.resolve(import.meta.dirname, '../../src/ExpressiveAvalonia/Assets/Avatars');
const outData = path.resolve(import.meta.dirname, '../../src/ExpressiveAvalonia/Controls/MaterialAvatarData.cs');

const PLACEHOLDER_ASSET = 'image-0012.bin';
const FAVICON_ASSET = 'image-0013.bin';

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/** Reads the IHDR of a PNG and fails loudly when the file is not an 8-bit RGBA PNG. */
function readPngHeader(file) {
  const bytes = fs.readFileSync(file);
  if (!bytes.subarray(0, 8).equals(PNG_SIGNATURE))
    throw new Error(`${path.basename(file)}: not a PNG`);
  const width = bytes.readUInt32BE(16);
  const height = bytes.readUInt32BE(20);
  const bitDepth = bytes[24];
  const colorType = bytes[25];
  if (bitDepth !== 8 || colorType !== 6)
    throw new Error(`${path.basename(file)}: expected 8-bit RGBA, got depth ${bitDepth} type ${colorType}`);
  return { bytes, width, height };
}

const packages = fs.readdirSync(root)
  .filter(name => /^3d-avatars-\d+--local-\d+$/.test(name))
  .map(name => ({
    index: Number(/^3d-avatars-(\d+)--/.exec(name)[1]),
    directory: name,
    sourceId: /--(local-\d+)$/.exec(name)[1],
  }))
  .sort((a, b) => a.index - b.index);

if (packages.length !== 30) throw new Error(`Expected 30 3D avatar packages, found ${packages.length}`);

fs.mkdirSync(outAssets, { recursive: true });
const entries = [];
let copied = 0;
for (const pkg of packages) {
  const variantDir = fs.readdirSync(path.join(root, pkg.directory, 'variants'))[0];
  const designPath = path.join(root, pkg.directory, 'variants', variantDir, 'design.json');
  const design = JSON.parse(fs.readFileSync(designPath, 'utf8'));
  const refs = Object.values(design.imageFills ?? {});
  if (refs.length !== 1) throw new Error(`${pkg.directory}: expected one image fill, found ${refs.length}`);
  // imageFills paths are relative to the design.json that references them.
  const source = path.resolve(path.dirname(designPath), refs[0]);
  const { bytes, width, height } = readPngHeader(source);
  if (width !== 1080 || height !== 1080)
    throw new Error(`${pkg.directory}: expected a 1080 x 1080 export, got ${width} x ${height}`);
  const file = `3d-avatar-${String(pkg.index).padStart(2, '0')}.png`;
  fs.writeFileSync(path.join(outAssets, file), bytes);
  copied += bytes.length;
  entries.push({
    sourceId: pkg.sourceId,
    name: design.document.name,
    index: pkg.index,
    file,
    source: path.basename(source),
  });
}

for (const [asset, file] of [[PLACEHOLDER_ASSET, 'thumbnail-placeholder.png'], [FAVICON_ASSET, 'favicon-symbol.png']]) {
  const source = path.join(root, 'assets', asset);
  const { bytes } = readPngHeader(source);
  fs.writeFileSync(path.join(outAssets, file), bytes);
}

const escape = value => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const lines = [
  '// <auto-generated>',
  '// Generated by tools/DesignAssets/generate-avatars.mjs from artifacts/design-system-anonymized.',
  '// Source identities, display names and image assignments are preserved verbatim.',
  '// Every photograph is the original 1080 px export copied byte-for-byte; nothing is resampled.',
  '// </auto-generated>',
  '',
  'namespace ExpressiveAvalonia.Controls;',
  '',
  '/// <summary>One exported 3D avatar. <paramref name="Id"/> is the design source identity.</summary>',
  'internal sealed record MaterialAvatarRecord(string Id, string Name, int Index, string File);',
  '',
  'internal static class MaterialAvatarData',
  '{',
  '    /// <summary>30 avatar photographs exported from the design source, in source order.</summary>',
  '    internal static readonly MaterialAvatarRecord[] Avatars =',
  '    [',
  ...entries.map(e =>
    `        new("${e.sourceId}", "${escape(e.name)}", ${e.index}, "${e.file}"),`),
  '    ];',
  '',
  '    /// <summary>The exported image placeholder used by both thumbnail building blocks.</summary>',
  '    internal const string ThumbnailPlaceholderFile = "thumbnail-placeholder.png";',
  '',
  '    /// <summary>The exported favicon symbol used by the favicon building block.</summary>',
  '    internal const string FaviconSymbolFile = "favicon-symbol.png";',
  '}',
  '',
];
fs.writeFileSync(outData, lines.join('\n'));

console.log(`Wrote ${entries.length} original-resolution avatars (${(copied / 1048576).toFixed(1)} MB) to ${path.relative(process.cwd(), outAssets)}`);
console.log(`Wrote ${path.relative(process.cwd(), outData)}`);
